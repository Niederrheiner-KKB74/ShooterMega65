"""Install reference-board player/enemies into a freshly generated Stage-1 asset set.

Consumes the reviewed indexed source, not PNGs at build time. Leaves landscape,
ground tank, projectiles and explosions exactly as generated by make_assets.
"""
import json
from pathlib import Path
import numpy as np
from PIL import Image
import make_assets as old

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'assets/art/reference-board/generated'
KINDS = ('fighter', 'bomber', 'helicopter', 'armoured_plane')


def main(out):
    out = Path(out)
    manifest = json.loads((ART / 'manifest.json').read_text())
    source = json.loads((ART / 'indexed-source.json').read_text())
    pixels = {(s['group'], s['frame']): np.frombuffer(bytes.fromhex(''.join(s['rows'])), dtype=np.uint8).reshape(s['height'], s['width']) for s in source}
    # Keep legacy frame names for the unchanged ground/combat systems.
    frames = [(name, pix, 0x2f, 16, 16) for name, pix in old.FRAMES if name != 'ENEMY']
    for kindno, kind in enumerate(KINDS):
        for n in range(3):
            p = np.rot90(pixels[kind, n], 2)  # enemy noses down
            h, w = p.shape
            padded = np.zeros((h, ((w+15)//16)*16), np.uint8)
            padded[:, (padded.shape[1]-w)//2:(padded.shape[1]-w)//2+w] = p
            frames.append((kind.upper()+str(n), padded, ((kindno+3)<<4)|15, w, h))
    glyphs=[bytes(64)]
    table=[]
    for name,pix,pal,visible_w,visible_h in frames:
        h,w=pix.shape[0]//8,pix.shape[1]//16
        base=len(glyphs)
        for col in range(w):
            for row in range(h):glyphs.append(old.ncm_glyph(pix[row*8:row*8+8,col*16:col*16+16]))
            glyphs.append(bytes(64))
        table.append(dict(name=name,base=base,w=w,h=h,pal=pal,cx=pix.shape[1]//2,cy=visible_h//2,halfw=visible_w//2,halfh=visible_h//2))
    if len(glyphs)>256 or any(t['base']>255 for t in table):raise ValueError('8-bit pixie glyph budget exceeded')
    (out/'pixies.bin').write_bytes(b''.join(glyphs))
    # Normal / left / right; keep only one pair resident at $5f000.
    sprites=bytearray()
    for frame in (4,3,5):
        p=np.zeros((24,32),np.uint8);p[:,4:28]=pixels['player',frame]
        for half in range(2):
            block=p[:,half*16:half*16+16].reshape(-1)
            sprites.extend(bytes((int(block[i])<<4)|int(block[i+1]) for i in range(0,len(block),2))+bytes(64))
    (out/'sprite.bin').write_bytes(sprites)
    (out/'sprpal.bin').write_bytes((ART/'player.sprpal.bin').read_bytes())
    pal=bytearray((out/'palette.bin').read_bytes())
    for i,kind in enumerate(KINDS):
        for n,c in enumerate(manifest['palettes'][kind]):
            for ch in range(3):pal[ch*256+(i+3)*16+n]=old.swap(c[ch])
    (out/'palette.bin').write_bytes(pal)
    inc=(out/'assets.inc').read_text()
    replaced=('.const FR_', '.const PIXIE_GLYPHS=', '.const PLAYER_FRAMES=', '.const AIR_ANIM_FRAMES=')
    inc='\n'.join(l for l in inc.splitlines() if not l.startswith(replaced))+'\n'
    inc+=f'.const PIXIE_GLYPHS={len(glyphs)}\n.const PLAYER_FRAMES=3\n.const AIR_ANIM_FRAMES=3\n'
    for i,t in enumerate(table):inc+=f'.const FR_{t["name"]}={i}\n'
    inc+='.const FR_ENEMY=FR_FIGHTER0\n'
    (out/'assets.inc').write_text(inc)
    lines=['// generated by integrate_aircraft.py - do not edit']
    for label,key in [('frame_base','base'),('frame_w','w'),('frame_h','h'),('frame_pal','pal'),('frame_hit_cx','cx'),('frame_hit_cy','cy'),('frame_hit_halfw','halfw'),('frame_hit_halfh','halfh')]:
        lines.append(label+': .byte '+','.join(str(t[key]) for t in table))
    lines.append('air_frame_first: .byte '+','.join('FR_'+k.upper()+'0' for k in KINDS))
    (out/'frames.inc').write_text('\n'.join(lines)+'\n')
    (out/'aircraft-layout.json').write_text(json.dumps(dict(frames=table,player_source_frames=[4,3,5],pixie_glyphs=len(glyphs)),indent=2)+'\n')
    # Render exactly the selected palettes/indices for review.
    rows=[]
    for name,pix,pal,_,_ in frames:
        colours=old.PAL_OBJ if pal==0x2f else manifest['palettes'][KINDS[(pal>>4)-3]]
        rgba=np.array([[tuple(colours[int(v)])+(255 if v else 0,) for v in row] for row in pix],np.uint8)
        im=Image.fromarray(rgba).resize((pix.shape[1]*6,pix.shape[0]*6),Image.Resampling.NEAREST)
        rows.append(im)
    sheet=Image.new('RGBA',(sum(im.width+6 for im in rows),144),(16,24,32,255));x=0
    for im in rows:sheet.paste(im,(x,0),im);x+=im.width+6
    sheet.save(out/'preview_pixies.png')
    Image.open(ART/'player.png').crop((4*24,0,5*24,24)).resize((144,144),Image.Resampling.NEAREST).save(out/'preview_player.png')
    print(f'reference aircraft: {len(table)} frames, {len(glyphs)} pixie glyphs, 3 streamed player pairs')
